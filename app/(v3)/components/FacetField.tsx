export default function FacetField({ variant, className }: { variant: "web" | "mobile"; className?: string }) {
  const facets = variant === "web" ? WEB : MOBILE;
  return (
    <svg
      className={["facets", `facets--${variant}`, className].filter(Boolean).join(" ")}
      viewBox={variant === "web" ? "0 0 720 520" : "0 0 390 240"}
      aria-hidden="true"
      focusable="false"
    >
      <g className="facets__drift">
        {facets.map(([points, fill], i) => (
          <polygon key={i} points={points} fill={fill} />
        ))}
      </g>
    </svg>
  );
}
